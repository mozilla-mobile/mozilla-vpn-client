import argparse
import json
import os
import sys

def parseClassList(args, file):
    result = []
    for entry in json.load(file):
        classlist = []
        for i in entry["classes"]:
            if i["className"] == args.parent:
                args.parent_header = entry["inputFile"]
                continue
            elif not "superClasses" in i:
                continue

            for sc in i["superClasses"]:
                if sc["name"] == args.parent:
                    classlist.append(i)
                    continue
        
        if len(classlist):
            entry["classes"] = classlist
            result.append(entry)

    return result

def formatClassList(args, classlist, file):
    print(f'/* Autogenerated by: {sys.argv[0]} */\n', file=file)

    # Assemble the list of headers to include.
    print("#include <QList>", file=file)
    print("#include <QObject>", file=file)
    if args.parent_header:
        print(f'#include "{args.parent_header}"', file=file)
    for entry in classlist:
        print(f'#include "{entry["inputFile"]}"', file=file)
    print('', file=file)

    # Generate a method that returns a list of testcases.
    print(f'QList<const QMetaObject*> {args.parent}::testcases() ' "{", file=file)
    print('  return QList<const QMetaObject*>({', file=file)
    for entry in classlist:
        for i in entry["classes"]:
            print(f'    &{i["className"]}::staticMetaObject,', file=file)
    print('  });', file=file)
    print('}', file=file)

def main():
    parser = argparse.ArgumentParser(description='Generate test lists from metaobject JSON')
    parser.add_argument('files', metavar='FILE', type=str, nargs='+',
                        help='JSON metaobject data to parse for test classes')
    parser.add_argument('-o', '--output', metavar='FILE', type=str,
                        help='Output file')
    parser.add_argument('-p', '--parent', metavar='CLASS', type=str,
                        required=True,
                        help='Parent class name to match')
    parser.add_argument('--parent-header', metavar="", type=str,
                        help='include filename for parent class')
    args = parser.parse_args()

    # Load the classes processed by moc.
    classlist = []
    for filename in args.files:
        with open(filename, 'r') as fp:
            classlist.extend(parseClassList(args, fp))

    if not args.output or args.output == '-':
        formatClassList(args, classlist, sys.stdout)
    else:
        with open(args.output, 'w') as fp:
            formatClassList(args, classlist, fp)

if __name__ == "__main__":
    main()
